//! The runner: a `cdylib` crate the CLI writes in the app's
//! `.nsh/miniprogram/runner`, linking NSH's generated `nsh_rust_app` (the
//! app's UI sets and root) with this platform's backend, built for
//! `wasm32-unknown-unknown` into the module the Mini Program loads.

use std::{
    fs,
    io::BufRead as _,
    path::{Path, PathBuf},
    process::{Command, Stdio},
};

use anyhow::{Context as _, bail};

/// The backend this CLI was built with: the checkout it was built in when it
/// is still there, `NSH_MINIPROGRAM_SOURCE` (a checkout) when set, else
/// this version's tag of the repository.
fn backend() -> String {
    let checkout = std::env::var_os("NSH_MINIPROGRAM_SOURCE")
        .map(PathBuf::from)
        .or_else(|| {
            Path::new(env!("CARGO_MANIFEST_DIR"))
                .parent()
                .and_then(Path::parent)
                .map(Path::to_path_buf)
        })
        .filter(|dir| dir.join("crates/nsh-platform-miniprogram/Cargo.toml").is_file());
    match checkout {
        Some(dir) => format!(
            "{{ path = {:?} }}",
            dir.join("crates/nsh-platform-miniprogram").to_string_lossy()
        ),
        None => format!(
            "{{ git = \"https://github.com/huacnlee/nsh-platform-miniprogram\", tag = \"v{}\" }}",
            env!("CARGO_PKG_VERSION")
        ),
    }
}

/// The value of `key = "…"` on a line of `manifest` that starts with it.
fn value<'a>(manifest: &'a str, line_start: &str, key: &str) -> Option<&'a str> {
    let line = manifest.lines().find(|l| l.starts_with(line_start))?;
    let rest = &line[line.find(&format!("{key} = \""))? + key.len() + 4..];
    Some(&rest[..rest.find('"')?])
}

/// Where NSH's generated crate takes `nsh-core` from, as the source of a
/// `[patch.crates-io]` entry for NSH's crate `name`: a checkout's path or a
/// Git repository at a branch, tag or revision; `None` for crates.io. The
/// runner takes NSH's crates from the same place, so the app and the
/// backend share one `nsh-core`.
fn nsh_source(rust_app_manifest: &str, name: &str) -> Option<String> {
    if let Some(core) = value(rust_app_manifest, "nsh-core = ", "path") {
        let checkout = Path::new(core).parent()?.parent()?;
        return Some(format!(
            "{{ path = {:?} }}",
            checkout.join("crates").join(name).to_string_lossy()
        ));
    }
    let git = value(rust_app_manifest, "nsh-core = ", "git")?;
    let reference = ["branch", "tag", "rev"]
        .into_iter()
        .find_map(|key| {
            value(rust_app_manifest, "nsh-core = ", key).map(|v| format!(", {key} = {v:?}"))
        })
        .unwrap_or_default();
    Some(format!("{{ git = {git:?}{reference} }}"))
}

/// The `[patch]` sections of NSH's generated workspace (`.nsh/rust`): how
/// it sends crates.io's and Git's NSH crates to the one checkout the app
/// builds with. The runner, a workspace of its own, takes them as they are,
/// so it resolves the app's crates as NSH's own workspace does.
fn workspace_patches(workspace_manifest: &str) -> String {
    let mut out = String::new();
    let mut in_patch = false;
    for line in workspace_manifest.lines() {
        if line.starts_with('[') {
            in_patch = line.starts_with("[patch");
        }
        if in_patch {
            out.push_str(line);
            out.push('\n');
        }
    }
    out
}

/// Writes the runner crate in `dir` for NSH's generated crate `rust_app`.
pub(crate) fn write(dir: &Path, rust_app: &Path) -> anyhow::Result<()> {
    let manifest = fs::read_to_string(rust_app.join("Cargo.toml"))
        .with_context(|| format!("reading {}", rust_app.display()))?;
    let package = value(&manifest, "name = ", "name")
        .context("NSH's rust-app crate has no package name")?;
    let workspace = rust_app
        .parent()
        .and_then(|ws| fs::read_to_string(ws.join("Cargo.toml")).ok())
        .map(|m| workspace_patches(&m))
        .unwrap_or_default();
    let patch = if !workspace.is_empty() {
        format!("\n# NSH's crates as NSH's generated workspace resolves them.\n{workspace}")
    } else {
        match (
            nsh_source(&manifest, "nsh-core"),
            nsh_source(&manifest, "nsh-engine"),
        ) {
            (Some(core), Some(engine)) => format!(
                "\n# The backend's NSH crates from where the app's come from.\n\
                 [patch.crates-io]\nnsh-core = {core}\nnsh-engine = {engine}\n"
            ),
            _ => String::new(),
        }
    };
    fs::create_dir_all(dir)?;
    fs::write(
        dir.join("Cargo.toml"),
        format!(
            "# Generated by nsh-platform-miniprogram: do not edit.\n\
             [package]\nname = \"nsh-miniprogram-runner\"\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\n\n\
             [lib]\npath = \"lib.rs\"\ncrate-type = [\"cdylib\"]\n\n\
             [dependencies]\nnsh_rust_app = {{ package = {package:?}, path = {:?} }}\n\
             nsh-platform-miniprogram = {}\n\n\
             # A Mini Program's package is small: the module is built for size.\n\
             [profile.release]\nopt-level = \"z\"\nlto = \"fat\"\ncodegen-units = 1\npanic = \"abort\"\nstrip = true\n\
             {patch}\n[workspace]\n",
            rust_app.to_string_lossy(),
            backend(),
        ),
    )?;
    fs::write(
        dir.join("lib.rs"),
        "//! The app's Mini Program module: NSH's engine with the app's root.\n\n\
         // The app's own UI sets (their fonts and files) without `nsh/base`'s,\n\
         // which serves TSX: the module links only the base components the app\n\
         // uses, and a Mini Program's package is small.\n\
         nsh_platform_miniprogram::app!(nsh_rust_app::app_ui_sets(), nsh_rust_app::root());\n",
    )?;
    fs::write(
        dir.join("build.rs"),
        "//! The module's stack: 8 MiB, as NSH's web runtime's.\n\n\
         fn main() {\n    if std::env::var(\"CARGO_CFG_TARGET_ARCH\").as_deref() == Ok(\"wasm32\") {\n        \
         println!(\"cargo:rustc-link-arg=-zstack-size=8388608\");\n    }\n}\n",
    )?;
    Ok(())
}

/// Builds the runner in `dir`; the module's path.
pub(crate) fn build(dir: &Path, verbose: bool) -> anyhow::Result<PathBuf> {
    println!("• building the app's WebAssembly module (cargo build --release)");
    let mut child = Command::new(std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into()))
        .args([
            "build",
            "--release",
            "--target",
            "wasm32-unknown-unknown",
            "--message-format=json-render-diagnostics",
        ])
        .current_dir(dir)
        .stdout(Stdio::piped())
        .stderr(if verbose { Stdio::inherit() } else { Stdio::piped() })
        .spawn()
        .context("running cargo")?;
    let mut module = None;
    for line in std::io::BufReader::new(child.stdout.take().context("cargo's output")?).lines() {
        let Ok(message) = serde_json::from_str::<serde_json::Value>(&line?) else {
            continue;
        };
        if message["reason"] == "compiler-artifact"
            && message["target"]["name"] == "nsh_miniprogram_runner"
        {
            module = message["filenames"]
                .as_array()
                .into_iter()
                .flatten()
                .filter_map(|f| f.as_str())
                .find(|f| f.ends_with(".wasm"))
                .map(PathBuf::from);
        }
    }
    let output = child.wait_with_output()?;
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        bail!(
            "the module did not build (rustup target add wasm32-unknown-unknown?)\n{stderr}"
        );
    }
    module.context("cargo built no .wasm")
}

#[cfg(test)]
mod tests {
    use super::*;

    const RUST_APP: &str = "[package]\nname = \"counter-rust-app\"\nversion = \"0.0.0\"\n\n\
        [dependencies]\nnsh-core = { path = \"/src/nsh/crates/nsh-core\" }\n\
        nsh-base = { path = \"/src/nsh/crates/nsh-base\", features = [\"highlight\"] }\n";

    #[test]
    fn reads_nsh_s_generated_crate() {
        assert_eq!(value(RUST_APP, "name = ", "name"), Some("counter-rust-app"));
        assert_eq!(
            nsh_source(RUST_APP, "nsh-engine").as_deref(),
            Some("{ path = \"/src/nsh/crates/nsh-engine\" }")
        );
        let registry = RUST_APP.replace("path = \"/src/nsh/crates/nsh-core\"", "version = \"=0.4.0\"");
        assert_eq!(nsh_source(&registry, "nsh-core"), None);
        let git = RUST_APP.replace(
            "path = \"/src/nsh/crates/nsh-core\"",
            "git = \"https://github.com/longbridge/nsh\", branch = \"main\"",
        );
        assert_eq!(
            nsh_source(&git, "nsh-engine").as_deref(),
            Some("{ git = \"https://github.com/longbridge/nsh\", branch = \"main\" }")
        );
    }

    #[test]
    fn takes_the_generated_workspace_s_patches() {
        let workspace = "[workspace]\nmembers = []\n\n[profile.web]\nopt-level = \"z\"\n\n\
            [patch.crates-io]\nnsh-core = { path = \"/c/crates/nsh-core\" }\n\n\
            [patch.\"https://github.com/longbridge/nsh\"]\nnsh-core = { path = \"/c/crates/nsh-core\" }\n";
        let patches = workspace_patches(workspace);
        assert!(patches.starts_with("[patch.crates-io]\n"), "{patches}");
        assert!(patches.contains("[patch.\"https://github.com/longbridge/nsh\"]"));
        assert!(!patches.contains("opt-level"));
    }

    #[test]
    fn the_runner_links_the_app_and_the_backend() {
        let dir = std::env::temp_dir().join(format!("nsh-mp-runner-{}", std::process::id()));
        let app = dir.join("rust-app");
        fs::create_dir_all(&app).unwrap();
        fs::write(app.join("Cargo.toml"), RUST_APP).unwrap();
        write(&dir.join("runner"), &app).unwrap();
        let manifest = fs::read_to_string(dir.join("runner/Cargo.toml")).unwrap();
        assert!(manifest.contains("nsh_rust_app = { package = \"counter-rust-app\", path = "));
        assert!(manifest.contains("nsh-core = { path = \"/src/nsh/crates/nsh-core\" }"));
        assert!(manifest.contains("crate-type = [\"cdylib\"]"));
        let lib = fs::read_to_string(dir.join("runner/lib.rs")).unwrap();
        assert!(lib.contains("app!(nsh_rust_app::app_ui_sets(), nsh_rust_app::root())"));
        fs::remove_dir_all(&dir).unwrap();
    }
}
